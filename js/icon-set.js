/**
 * `[data-icon]` daşıyan hər elementi uyğun SVG ilə doldurur.
 *
 * İDEMPOTENT: içində artıq `<svg>` varsa toxunmur — dinamik render-dən sonra
 * təkrar çağırmaq təhlükəsizdir (feed/chat siyahıları yenidən qurulur).
 *
 * @param {ParentNode} [root=document] yalnız bu alt-ağac boyanır
 */
export function paintIcons(root = document){
  for(const node of root.querySelectorAll('[data-icon]')){
    const d = ICONS[node.dataset.icon];
    if(!d || node.querySelector('svg')) continue;
    // Nişan (badge) kimi qardaş elementlər qorunur: yalnız MƏTN qovşaqları silinir.
    for(const child of [...node.childNodes]) if(child.nodeType === 3) child.remove();
    node.prepend(SVG(d, { w: node.dataset.iconSize || '18', h: node.dataset.iconSize || '18' }));
  }
}
